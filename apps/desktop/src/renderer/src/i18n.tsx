const STORAGE_KEY = 'editorLang'

interface I18nValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  tl: (label: string) => string
}

const I18nContext = createContext<I18nValue>({ lang: 'zh', setLang: () => undefined, t: (k) => k, tl: (l) => l })

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem(STORAGE_KEY)
    return saved === 'en' || saved === 'jp' ? saved : 'zh'
  })
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      // ignore
    }
  }, [])
  const value = useMemo<I18nValue>(() => {
    const t = (key: string, vars?: Record<string, string | number>) => {
      let text = dict[lang][key] ?? dict.zh[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v))
      }
      return text
    }
    const tl = (label: string) => labelDict[lang][label] ?? label
    return { lang, setLang, t, tl }
  }, [lang, setLang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  return useContext(I18nContext)
}