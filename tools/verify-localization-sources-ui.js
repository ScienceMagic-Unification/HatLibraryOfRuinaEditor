(async () => {
  const root = window.__sourceTestMod, state = () => window.__store.getState()
  const wait = () => new Promise((done) => setTimeout(done, 150))
  const check = (ok, message) => { if (!ok) throw new Error(message + '\n' + document.body.innerText.slice(-1800)) }
  const buttons = () => Array.from(document.querySelectorAll('button'))
  const click = async (node, name) => { check(node, 'Missing ' + name); node.click(); await wait() }
  const action = (label) => click(buttons().find((b) => b.textContent.trim() === label), label)
  const input = async (el, value) => {
    check(el, 'Missing editable field')
    Object.getOwnPropertyDescriptor(Object.getPrototypeOf(el), 'value').set.call(el, value)
    el.dispatchEvent(new Event('input', { bubbles: true }))
    await wait()
  }
  const choose = async (trigger, label) => {
    trigger.focus()
    trigger.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }))
    await wait()
    const option = [...document.querySelectorAll('[role=option]')].find((o) => o.textContent.includes(label))
    check(option, 'Missing option ' + label)
    option.focus()
    option.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }))
    await wait()
  }
  const area = (value) => [...document.querySelectorAll('textarea')].find((e) => e.value === value)
  const sourcePath = (lang, file) => root + '/Assemblies/Localize/' + lang + '/' + file
  const read = (lang, file) => window.api.readTextFile(sourcePath(lang, file))
  const a = 'BattleCardAbilities/Hat_Alpha.xml', b = 'BattleCardAbilities/Beta_cn.xml'
  const oldA = await read('cn', a), oldEnglish = await read('en', b)
  await state().openMod(root)
  state().setHatEnabled(true)
  await state().setActiveModule('cardability'); await wait()
  const docTrigger = () => document.querySelector('[role=combobox][title]')
  await choose(docTrigger(), '统合视图 · 简体中文')
  const rows = () => [...document.querySelectorAll('[data-scrollkey=cardability] .cursor-pointer')]
  check(rows().length === 3, 'Only three Chinese rows')
  await click(rows().find((r) => r.textContent.includes('Beta_cn.xml') && r.textContent.includes('Shared')), 'second Shared')
  await input(area('B-cn'), 'modified')
  await action('新增')
  await click([...document.querySelectorAll('[role=dialog] button')].find((e) => e.textContent === 'Beta_cn.xml'), 'add destination')
  check(state().primaryDocPath.cardability.endsWith('Beta_cn.xml'), 'target selected')
  check(await state().saveModule('cardability'), 'save module')
  check((await read('cn', a)) === oldA && (await read('en', b)) === oldEnglish, 'other sources byte-identical')
  const changed = await read('cn', b)
  check(changed.includes('modified') && changed.includes('<!--B-->') && changed.includes('keep="yes"') && changed.includes('ID="1"'), 'write-back/comments/new row')
  await choose(docTrigger(), 'Hat_Alpha.xml')
  check(rows().length === 1, 'single source view')
  await state().setActiveModule('cardinfo'); await wait()
  check(document.body.innerText.includes('Second-cn'), 'card name in second source')
  const keyword = document.querySelector('[data-keyword-id="Hat_Enchantments_Throughout_Dice_Keyword"]')
  check(keyword?.textContent === '贯通' && keyword.querySelector('img')?.naturalWidth > 0, 'ability from second source and icon')
  await click(keyword.closest('.cursor-pointer'), 'ability jump')
  check(state().activeModuleId === 'cardability' && state().primaryDocPath.cardability.endsWith('Beta_cn.xml'), 'jump to owner')
  await choose(docTrigger(), '统合视图 · English')
  check(rows().length === 3, 'English source group despite cn filename')
  await click(rows().find((r) => r.textContent.includes('SplitOnly')), 'English ability')
  check(document.querySelector('[data-keyword-id="Hat_Enchantments_Throughout_Dice_Keyword"]')?.textContent === 'Piercing', 'English rich preview')

  const red = 'EffectTexts/Red.xml', blue = 'EffectTexts/Blue.xml'
  const oldBlue = await read('cn', blue)
  await state().setActiveModule('mod-regex'); await wait()
  const redRow = buttons().find((e) => e.textContent.includes('Red-cn') && e.textContent.includes('Red.xml'))
  await click(redRow, 'source-qualified keyword')
  await input([...document.querySelectorAll('input')].find((el) => el.value === 'Red-cn'), 'New-Red')
  await action('保存本模块')
  check((await read('cn', red)).includes('New-Red') && (await read('cn', red)).includes('<!--Red-->') && (await read('cn', blue)) === oldBlue, 'keyword writes only to its source')
  await action('OK')
  const regexSource = () => [...document.querySelectorAll('[role=combobox]')].find((e) => /统合视图|Red.xml|Blue.xml/.test(e.textContent))
  await choose(regexSource(), 'Blue.xml')
  check(!buttons().some((e) => e.textContent.includes('New-Red')), 'single regex source')
  await choose(regexSource(), '统合视图')
  await action('新增')
  await click([...document.querySelectorAll('[role=dialog] button')].find((e) => e.textContent === 'Red.xml'), 'new keyword source')
  check((await read('cn', red)).includes('NewKeyword_') && (await read('cn', blue)) === oldBlue, 'new keyword belongs to selected source')
  await state().openMod(root); await wait()
  await state().openWorkspaceAndSelect('cardability', 'SplitOnly'); await wait()
  check(state().primaryDocPath.cardability.endsWith('Beta_cn.xml'), 'reloaded from source')
  await window.api.saveFile(root + '/../result.txt', 'PASS: combined/single views, duplicate IDs, source chooser, comments, language folders, linked preview, icons, jump, Mod regex write-back and reload.')
})()
