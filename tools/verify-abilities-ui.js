(async () => {
  const root = window.__keywordTestRoot, store = window.__store
  const saved = Object.fromEntries(['lastModPath', 'hatSingularityEnabled'].map((k) => [k, localStorage.getItem(k)]))
  const wait = () => new Promise((r) => setTimeout(r, 250))
  const check = (v, message) => { if (!v) throw new Error(message) }
  try {
    const manifest = JSON.parse(await window.api.readTextFile(root + '/apps/desktop/src/renderer/src/assets/abilities-manifest.json'))
    const resources = JSON.parse(await window.api.readTextFile(root + '/apps/desktop/src/renderer/src/assets/plugins/manifest.json'))
    await store.getState().openMod(root + '/docs/verification/keyword-mod')
    store.getState().setHatEnabled(true)
    await store.getState().setActiveModule('singularity-abilities'); await wait()
    const page = document.querySelector('[data-testid="singularity-abilities"]')
    check(page && page.textContent.includes(manifest.plugins.find((p) => p.plugin === 'HatSingularity.Enchantments').version), 'Ability workspace and source version')
    check(page.querySelector('textarea[readonly]').value === '(~HatKeyword id="Hat_Enchantments_ExhaustDice_Description_Keyword"/~)', 'Read-only dedicated exhaustion text')
    check(!page.textContent.includes('EnchantmentDiceAbility') && !page.querySelector('pre'), 'Only actual abilities, no C# tutorial or XML guide')
    const exhaustion = page.querySelector('[data-testid="ability-description"] [data-keyword-id="Hat_Enchantments_ExhaustDice_Description_Keyword"]')
    check(exhaustion?.textContent === '佚亡' && exhaustion.querySelector('img')?.naturalWidth > 0, 'XML-driven exhaustion icon and name')
    const filters = page.querySelectorAll('select')
    filters[0].value = 'card'; filters[0].dispatchEvent(new Event('change', { bubbles: true })); await wait()
    check(!page.querySelector('textarea') && page.textContent.includes('没有提供'), 'Truthful empty card category')
    filters[0].value = 'dice'; filters[0].dispatchEvent(new Event('change', { bubbles: true })); await wait()
    filters[1].value = 'en'; filters[1].dispatchEvent(new Event('change', { bubbles: true })); await wait()
    check(page.querySelector('textarea').value === '(~HatKeyword id="Hat_Enchantments_ExhaustDice_Description_Keyword"/~)', 'Original English resource retained')
    check(page.querySelector('[data-testid="ability-description"] [data-keyword-id="Hat_Enchantments_ExhaustDice_Description_Keyword"]')?.textContent === 'Exhaust', 'Dedicated English exhaustion name')
    const search = [...page.querySelectorAll('input')].find((e) => !e.readOnly)
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(search, 'SharedCounter')
    search.dispatchEvent(new Event('input', { bubbles: true })); await wait()
    check(page.textContent.includes('命中 1'), 'Shared ability-list search')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(search, '')
    search.dispatchEvent(new Event('input', { bubbles: true })); await wait()
    filters[1].value = 'cn'; filters[1].dispatchEvent(new Event('change', { bubbles: true })); await wait()
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(search, 'ShieldBash')
    search.dispatchEvent(new Event('input', { bubbles: true })); await wait()
    check(page.textContent.includes('命中 4'), 'Four shield bash variants')
    const shieldIds = manifest.abilities.filter((a) => a.id.includes('ShieldBash')).map((a) => a.id)
    for (const id of shieldIds) {
      const row = [...page.querySelectorAll('[data-scrollkey="singularity-abilities"] .cursor-pointer')].find((e) => e.textContent.includes(id))
      check(row, 'Shield bash list row ' + id)
      row.click(); await wait()
      const keyword = id.replace(/_Dice$/, '_Keyword')
      check(page.querySelector('textarea[readonly]').value === `(~HatKeyword id="${keyword}"/~)`, 'Original shield bash XML text ' + id)
      const preview = page.querySelector(`[data-testid="ability-description"] [data-keyword-id="${keyword}"]`)
      check(preview?.textContent.includes('盾击') && preview.querySelector('img')?.naturalWidth > 0, 'Shield bash icon and name ' + id)
    }
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(search, 'Throughout')
    search.dispatchEvent(new Event('input', { bubbles: true })); await wait()
    check(page.textContent.includes('命中 1'), 'Throughout search')
    const throughoutRow = [...page.querySelectorAll('[data-scrollkey="singularity-abilities"] .cursor-pointer')].find((e) => e.textContent.includes('Hat_Enchantments_Throughout_Dice'))
    check(throughoutRow, 'Throughout dice ability listed')
    throughoutRow.click(); await wait()
    for (const [language, name] of [['en', 'Piercing'], ['jp', '突破'], ['kr', '돌파'], ['cn', '贯通']]) {
      filters[1].value = language; filters[1].dispatchEvent(new Event('change', { bubbles: true })); await wait()
      check(page.querySelector('textarea[readonly]').value === '(~HatKeyword id="Hat_Enchantments_Throughout_Dice_Keyword"/~)', 'Original Throughout XML ' + language)
      const preview = page.querySelector('[data-testid="ability-description"] [data-keyword-id="Hat_Enchantments_Throughout_Dice_Keyword"]')
      check(preview?.textContent === name && preview.querySelector('img')?.naturalWidth > 0, 'Throughout name and icon ' + language)
      const resource = resources.resources.find((r) => r.plugin === 'HatSingularity.Enchantments' && r.language === language && r.name.endsWith('.DiceEffects.xml'))
      const xml = new DOMParser().parseFromString(await window.api.readTextFile(root + '/apps/desktop/src/renderer/src/assets/plugins/' + resource.path), 'text/xml')
      const originalDetail = xml.querySelector('[ID="Hat_Enchantments_Throughout_Dice_Keyword"] Desc').textContent
      check(preview.title.includes(originalDetail), 'Throughout detail tooltip ' + language)
    }
    await window.api.saveFile(root + '/docs/verification/abilities-ui-result.txt', `PASS: ${manifest.abilities.length} abilities; Throughout four-language name, icon, original XML and detail tooltip; four shield bash variants; exhaustion icon/name; category and search filters.`)
    await new Promise((r) => setTimeout(r, 1200))
  } finally {
    for (const [key, val] of Object.entries(saved)) if (val === null) localStorage.removeItem(key); else localStorage.setItem(key, val)
  }
})()
